#!/usr/bin/env python3
"""Generate small UI icons as LVGL 8 alpha-only images (src/ui_icons.c).

Alpha-only (LV_IMG_CF_ALPHA_4BIT) images carry no color: LVGL paints them
with the widget's img_recolor style, so the firmware can tint them freely
(e.g. flash the drone icon blue/red). Drawn at 4x and downsampled.

Usage: python3 tools/gen_ui_icons.py   (run from the project root)
"""
import math
from PIL import Image, ImageDraw

SS = 4


def drone(n):
    """Quadcopter seen from above: body, four arms, four rotor rings."""
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)
    c = n / 2
    arm = n * 0.335
    w = max(2, int(n * 0.09))
    r_rotor = n * 0.135
    ring = max(2, int(n * 0.07))
    for k in range(4):
        a = math.pi / 4 + k * math.pi / 2
        x, y = c + math.cos(a) * arm, c + math.sin(a) * arm
        d.line([(c, c), (x, y)], fill=255, width=w)
        d.ellipse([x - r_rotor, y - r_rotor, x + r_rotor, y + r_rotor], outline=255, width=ring)
        d.ellipse([x - n * 0.03, y - n * 0.03, x + n * 0.03, y + n * 0.03], fill=255)  # hub
    b = n * 0.10
    d.rounded_rectangle([c - b, c - b, c + b, c + b], radius=b * 0.4, fill=255)
    return img


def wave(n):
    """Two parallel rows of rolling sea waves."""
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)
    w = max(2, int(n * 0.12))
    for yc in (n * 0.32, n * 0.70):
        pts = []
        for i in range(0, 101):
            x = n * 0.05 + (n * 0.90) * i / 100
            pts.append((x, yc - math.sin((i / 100) * 2 * math.pi * 1.5) * n * 0.10))
        d.line(pts, fill=255, width=w, joint="curve")
    return img


def volcano(n):
    """Volcano cone with a crater notch and a puffy ash plume above it."""
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)
    d.polygon([(n * 0.04, n * 0.96), (n * 0.36, n * 0.46), (n * 0.43, n * 0.52), (n * 0.50, n * 0.47),
               (n * 0.57, n * 0.52), (n * 0.64, n * 0.46), (n * 0.96, n * 0.96)], fill=255)
    for cx, cy, r in ((0.50, 0.33, 0.085), (0.38, 0.22, 0.095), (0.60, 0.17, 0.11), (0.47, 0.09, 0.075)):
        d.ellipse([n * (cx - r), n * (cy - r), n * (cx + r), n * (cy + r)], fill=255)
    return img


def plane(n):
    """Airliner seen from above, nose up and to the right (taking off)."""
    big = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(big)
    c = n / 2
    pts = [  # nose up, drawn upright then rotated
        (0.50, 0.04), (0.56, 0.12), (0.56, 0.38), (0.94, 0.58), (0.94, 0.66), (0.56, 0.56), (0.56, 0.80),
        (0.68, 0.90), (0.68, 0.96), (0.50, 0.92), (0.32, 0.96), (0.32, 0.90), (0.44, 0.80), (0.44, 0.56),
        (0.06, 0.66), (0.06, 0.58), (0.44, 0.38), (0.44, 0.12)]
    d.polygon([(x * n, y * n) for x, y in pts], fill=255)
    return big.rotate(-45, resample=Image.BICUBIC, center=(c, c))


ICONS = [("drone", drone, 22), ("wave", wave, 22), ("wave_s", wave, 16), ("volcano", volcano, 22),
         ("plane", plane, 22)]


def to_alpha4(img):
    w, h = img.size
    px = img.tobytes()
    out = bytearray()
    for y in range(h):
        row = px[y * w:(y + 1) * w]
        for x in range(0, w, 2):
            hi = row[x] >> 4
            lo = (row[x + 1] >> 4) if x + 1 < w else 0
            out.append((hi << 4) | lo)
    return out


def main():
    c = ["// Generated by tools/gen_ui_icons.py - do not edit by hand.", '#include "ui_icons.h"', ""]
    h = ["#pragma once", "", "// Generated by tools/gen_ui_icons.py", "#include <lvgl.h>", "",
         "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    preview = Image.new("RGB", (len(ICONS) * 64 + 16, 72), (21, 23, 26))
    for i, (name, fn, size) in enumerate(ICONS):
        img = fn(size * SS).resize((size, size), Image.LANCZOS)
        data = to_alpha4(img)
        sym = f"ui_{name}"
        c.append(f"static const uint8_t {sym}_map[] = {{")
        for k in range(0, len(data), 24):
            c.append("  " + ", ".join(f"0x{b:02x}" for b in data[k:k + 24]) + ",")
        c.append("};")
        c.append(f"const lv_img_dsc_t {sym} = {{")
        c.append(f"  .header = {{.cf = LV_IMG_CF_ALPHA_4BIT, .always_zero = 0, .reserved = 0, "
                 f".w = {size}, .h = {size}}},")
        c.append(f"  .data_size = {len(data)},")
        c.append(f"  .data = {sym}_map,")
        c.append("};")
        c.append("")
        h.append(f"extern const lv_img_dsc_t {sym};")
        # preview: blue and red tints, scaled up
        for j, col in enumerate(((33, 150, 243), (244, 67, 54))):
            tile = Image.new("RGB", (size, size), col)
            bg = Image.new("RGB", (size, size), (21, 23, 26))
            bg.paste(tile, (0, 0), img)
            preview.paste(bg.resize((size * 2 - 14, size * 2 - 14), Image.NEAREST), (8 + i * 64 + j * 32, 14))
    h += ["", "#ifdef __cplusplus", "}", "#endif", ""]
    open("src/ui_icons.c", "w").write("\n".join(c))
    open("src/ui_icons.h", "w").write("\n".join(h))
    preview.save("tools/ui_icons_preview.png")


if __name__ == "__main__":
    main()
