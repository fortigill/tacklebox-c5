#!/usr/bin/env python3
"""Generate the weather icons as LVGL 8 image descriptors (src/wx_icons.c).

Icons are drawn at 4x and downsampled for anti-aliasing, then written as
LV_IMG_CF_TRUE_COLOR_ALPHA (RGB565 little-endian + 8-bit alpha, matching
LV_COLOR_DEPTH 16 / LV_COLOR_16_SWAP 0).

Usage: python3 tools/gen_wx_icons.py   (run from the project root)
"""
import math
from PIL import Image, ImageDraw

SIZES = {"s": 28, "l": 64}
SS = 4  # supersampling factor

SUN = (255, 193, 7)
CLOUD = (225, 230, 236)
CLOUD_DARK = (150, 160, 172)
RAIN = (79, 166, 255)
SNOW = (240, 248, 255)
BOLT = (255, 214, 0)
FOG = (176, 186, 197)
WIND = (170, 210, 235)


def canvas(n):
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def sun(d, n, cx, cy, r, rays=True):
    if rays:
        w = max(2, int(n * 0.06))
        for i in range(8):
            a = i * math.pi / 4
            x1, y1 = cx + math.cos(a) * r * 1.35, cy + math.sin(a) * r * 1.35
            x2, y2 = cx + math.cos(a) * r * 1.85, cy + math.sin(a) * r * 1.85
            d.line([(x1, y1), (x2, y2)], fill=SUN, width=w)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=SUN)


def cloud(d, n, x, y, w, color):
    """Cloud with its bounding box starting at (x, y), width w."""
    h = w * 0.55
    d.ellipse([x + w * 0.05, y + h * 0.35, x + w * 0.45, y + h * 1.0], fill=color)
    d.ellipse([x + w * 0.22, y + h * 0.0, x + w * 0.70, y + h * 0.85], fill=color)
    d.ellipse([x + w * 0.52, y + h * 0.25, x + w * 0.95, y + h * 1.0], fill=color)
    d.rounded_rectangle([x + w * 0.25, y + h * 0.6, x + w * 0.75, y + h * 1.0], radius=h * 0.2,
                        fill=color)


def drops(d, n, color, count, long_=True):
    w = max(2, int(n * 0.07))
    top = n * 0.68
    ln = n * (0.22 if long_ else 0.12)
    for i in range(count):
        x = n * (0.28 + i * (0.44 / max(1, count - 1)))
        d.line([(x, top), (x - ln * 0.35, top + ln)], fill=color, width=w)


def flakes(d, n):
    r = n * 0.07
    for i, fx in enumerate((0.3, 0.5, 0.7)):
        cx, cy = n * fx, n * (0.80 if i % 2 == 0 else 0.90)
        w = max(2, int(n * 0.04))
        for k in range(3):
            a = k * math.pi / 3
            d.line([(cx - math.cos(a) * r, cy - math.sin(a) * r),
                    (cx + math.cos(a) * r, cy + math.sin(a) * r)], fill=SNOW, width=w)


def icon_sun(n):
    img, d = canvas(n)
    sun(d, n, n / 2, n / 2, n * 0.24)
    return img


def icon_partly(n):
    img, d = canvas(n)
    sun(d, n, n * 0.36, n * 0.36, n * 0.17)
    cloud(d, n, n * 0.18, n * 0.38, n * 0.80, CLOUD)
    return img


def icon_cloud(n):
    img, d = canvas(n)
    cloud(d, n, n * 0.04, n * 0.22, n * 0.92, CLOUD)
    return img


def icon_fog(n):
    img, d = canvas(n)
    cloud(d, n, n * 0.08, n * 0.08, n * 0.84, CLOUD_DARK)
    w = max(2, int(n * 0.07))
    for i, (a, b) in enumerate(((0.12, 0.80), (0.22, 0.92), (0.10, 0.70))):
        y = n * (0.64 + i * 0.13)
        d.line([(n * a, y), (n * b, y)], fill=FOG, width=w)
    return img


def icon_drizzle(n):
    img, d = canvas(n)
    cloud(d, n, n * 0.06, n * 0.06, n * 0.88, CLOUD_DARK)
    drops(d, n, RAIN, 3, long_=False)
    return img


def icon_rain(n):
    img, d = canvas(n)
    cloud(d, n, n * 0.06, n * 0.04, n * 0.88, CLOUD_DARK)
    drops(d, n, RAIN, 4)
    return img


def icon_snow(n):
    img, d = canvas(n)
    cloud(d, n, n * 0.06, n * 0.04, n * 0.88, CLOUD)
    flakes(d, n)
    return img


def icon_storm(n):
    img, d = canvas(n)
    cloud(d, n, n * 0.06, n * 0.02, n * 0.88, CLOUD_DARK)
    pts = [(0.55, 0.52), (0.36, 0.78), (0.50, 0.78), (0.42, 0.98), (0.68, 0.68), (0.53, 0.68),
           (0.62, 0.52)]
    d.polygon([(x * n, y * n) for x, y in pts], fill=BOLT)
    return img


def icon_wind(n):
    img, d = canvas(n)
    w = max(2, int(n * 0.075))
    for y, length, curl in ((0.32, 0.62, 0.12), (0.52, 0.78, 0.14), (0.72, 0.50, 0.10)):
        x0, x1, yy = n * 0.08, n * (0.08 + length), n * y
        d.line([(x0, yy), (x1, yy)], fill=WIND, width=w)
        r = n * curl
        d.arc([x1 - r, yy - 2 * r, x1 + r, yy], start=90, end=360, fill=WIND, width=w)
    return img


ICONS = [
    ("sun", icon_sun), ("partly", icon_partly), ("cloud", icon_cloud), ("fog", icon_fog),
    ("drizzle", icon_drizzle), ("rain", icon_rain), ("snow", icon_snow), ("storm", icon_storm),
    ("wind", icon_wind),
]


def to_lvgl(img):
    out = bytearray()
    raw = img.tobytes()  # RGBA
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
        if a == 0:
            r = g = b = 0
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        out += bytes((c & 0xFF, c >> 8, a))
    return out


def main():
    lines = [
        "// Generated by tools/gen_wx_icons.py - do not edit by hand.",
        '#include "wx_icons.h"',
        "",
    ]
    for name, fn in ICONS:
        for tag, size in SIZES.items():
            big = fn(size * SS)
            img = big.resize((size, size), Image.LANCZOS)
            data = to_lvgl(img)
            sym = f"wx_{name}_{tag}"
            lines.append(f"static const uint8_t {sym}_map[] = {{")
            for i in range(0, len(data), 24):
                lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
            lines.append("};")
            lines.append(f"const lv_img_dsc_t {sym} = {{")
            lines.append(f"  .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, "
                         f".reserved = 0, .w = {size}, .h = {size}}},")
            lines.append(f"  .data_size = {len(data)},")
            lines.append(f"  .data = {sym}_map,")
            lines.append("};")
            lines.append("")
    open("src/wx_icons.c", "w").write("\n".join(lines))

    hdr = ["#pragma once", "", "// Generated by tools/gen_wx_icons.py", "#include <lvgl.h>", "",
           "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    for name, _ in ICONS:
        for tag in SIZES:
            hdr.append(f"extern const lv_img_dsc_t wx_{name}_{tag};")
    hdr += ["", "#ifdef __cplusplus", "}", "#endif", ""]
    open("src/wx_icons.h", "w").write("\n".join(hdr))

    # Contact sheet for eyeballing the result
    sheet = Image.new("RGBA", (len(ICONS) * 72, 72 + 36), (30, 33, 38, 255))
    for i, (name, fn) in enumerate(ICONS):
        for tag, size in SIZES.items():
            img = fn(size * SS).resize((size, size), Image.LANCZOS)
            pos = (i * 72 + 4, 4) if tag == "l" else (i * 72 + 22, 72)
            sheet.alpha_composite(img, pos)
    sheet.save("tools/wx_icons_preview.png")


if __name__ == "__main__":
    main()
